export const UI: Record<Lang, Record<UiKey, string>> = { ro, en };

/** Text for `key` in `lang`, with {placeholders} filled in. */
export function tr(key: UiKey, lang: Lang, vars?: Record<string, string | number>): string {
  const s = UI[lang][key] ?? ro[key];
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : s;
}

/** The active child's language (Romanian until a parent or the child picks English). */
export const useLang = (): Lang => useProfile((s) => s.active().lang ?? 'ro');

/** t('key', {n: 3}) in the active child's language; re-renders when the language changes. */
export function useT() {
  const lang = useLang();
  return (key: UiKey, vars?: Record<string, string | number>) => tr(key, lang, vars);
}
