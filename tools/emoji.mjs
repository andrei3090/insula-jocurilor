// Extracts the few Fluent Emoji (MIT, Microsoft) the app uses into a small TS module,
// so the 9 MB icon set never reaches the bundle. Usage: npm run emoji
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve('@iconify-json/fluent-emoji-flat/icons.json'), 'utf8'));

export const NAMES =
  `panda bear polar-bear koala turtle dolphin tropical-fish fish octopus crab unicorn butterfly lady-beetle
hedgehog honeybee snail frog owl duck rabbit-face cat-face dog-face monkey-face elephant giraffe penguin baby-chick fox lion
pig-face cow-face spouting-whale whale shark seal jellyfish lobster shrimp crown glowing-star star sparkles rainbow
cherry-blossom sunflower tulip hibiscus rose four-leaf-clover mushroom strawberry watermelon red-apple green-apple banana
grapes cherries tangerine pear lemon peach pineapple birthday-cake cookie lollipop doughnut soft-ice-cream balloon
wrapped-gift spiral-shell sailboat canoe desert-island gem-stone palm-tree water-wave sun cloud crescent-moon
high-heeled-shoe ballet-shoes bowl-with-spoon chair bed teddy-bear honey-pot carrot castle magic-wand crystal-ball
red-heart pink-heart artist-palette paintbrush crayon kite umbrella rocket anchor compass alarm-clock mantelpiece-clock
coin money-bag ring bell drum seedling herb deciduous-tree evergreen-tree snowflake fire droplet house`.split(
    /\s+/,
  );

const out = {};
const missing = [];
for (const n of NAMES) {
  const name = set.icons[n] ? n : set.aliases?.[n]?.parent;
  if (!name || !set.icons[name]) {
    missing.push(n);
    continue;
  }
  out[n] = set.icons[name].body;
}
const body = Object.entries(out)
  .map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`)
  .join('\n');
writeFileSync(
  new URL('../src/art/emoji-data.ts', import.meta.url),
  `// Generated by tools/emoji.mjs from @iconify-json/fluent-emoji-flat (Fluent Emoji, MIT licence, Microsoft).\n// Do not edit by hand.\nexport const EMOJI = {\n${body}\n} as const;\n\nexport type EmojiName = keyof typeof EMOJI;\n`,
);
console.log(
  `emoji: ${Object.keys(out).length} icons${missing.length ? `, missing: ${missing.join(' ')}` : ''}`,
);
