function extract(names) {
  const out = {};
  const missing = [];
  for (const n of names) {
    const name = set.icons[n] ? n : set.aliases?.[n]?.parent;
    if (!name || !set.icons[name]) {
      missing.push(n);
      continue;
    }
    out[n] = set.icons[name].body;
  }
  return { out, missing };
}

function write(file, exportName, typeName, names) {
  const { out, missing } = extract(names);
  const body = Object.entries(out)
    .map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`)
    .join('\n');
  writeFileSync(
    new URL(file, import.meta.url),
    `// Generated by tools/emoji.mjs from @iconify-json/fluent-emoji-flat (Fluent Emoji, MIT licence, Microsoft).\n// Do not edit by hand.\nexport const ${exportName} = {\n${body}\n} as const;\n\nexport type ${typeName} = keyof typeof ${exportName};\n`,
  );
  console.log(
    `${file}: ${Object.keys(out).length} icons${missing.length ? `, missing: ${missing.join(' ')}` : ''}`,
  );
}

